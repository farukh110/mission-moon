// Downloads the narration as MP3 files, once, while preparing the game (needs internet).
// The finished game plays these local files, so it works fully offline.
//
//   npm run audio
//
// Each { ur, en } line found in data/ is spoken in simple English with an Asian (Indian English) voice.
// It becomes public/audio/ur/<id>.mp3, and data/voiceFiles.ts maps the line's `ur` key -> file.
import { EdgeTTS } from "node-edge-tts";
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const VOICE = "en-IN-NeerjaNeural";
const OUT = "public/audio/ur";
mkdirSync(OUT, { recursive: true });

const files = [...readdirSync("data/stages").map((f) => `data/stages/${f}`), "data/stages.ts", "data/narration.ts", "data/moonStations.ts"];
const STR = '"(?:[^"\\\\]|\\\\.)*"';
const QUOTED = new RegExp(STR, "g");
const PAIR = new RegExp(`\\bur:\\s*(${STR})\\s*,\\s*en:\\s*(${STR})`, "g");
const CARD = new RegExp(`title:\\s*(${STR}),\\s*text:\\s*(${STR})`, "g");
const NUMBERS = { 1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five" };
const lines = new Map(); // ur key -> English text to speak
for (const file of files) {
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(PAIR)) {
    const en = JSON.parse(m[2]);
    lines.set(JSON.parse(m[1]), NUMBERS[en] ?? en);
  }
}
// the Moon journey cards: Urdu list + English title and text
const journey = readFileSync("data/stages/journey.ts", "utf8");
const urdu = journey.match(/JOURNEY_URDU: string\[\] = \[([\s\S]*?)\n\];/);
const cards = [...journey.matchAll(CARD)];
if (urdu) [...urdu[1].matchAll(QUOTED)].forEach((m, i) => cards[i] && lines.set(JSON.parse(m[0]), `${JSON.parse(cards[i][1])}. ${JSON.parse(cards[i][2])}`));

const idOf = (text) => createHash("sha1").update(text).digest("hex").slice(0, 12);
const tts = new EdgeTTS({ voice: VOICE, lang: "en-IN", outputFormat: "audio-24khz-48kbitrate-mono-mp3", rate: "-8%", timeout: 60000 });

const map = {};
let made = 0;
for (const [key, text] of lines) {
  const id = idOf(text);
  const path = `${OUT}/${id}.mp3`;
  map[key] = `/audio/ur/${id}.mp3`;
  if (existsSync(path)) continue;
  for (let attempt = 1; ; attempt++) {
    try {
      await tts.ttsPromise(text, path);
      made++;
      console.log(`${made}. ${text.slice(0, 50)}`);
      break;
    } catch (error) {
      if (attempt >= 4) throw error;
      await new Promise((r) => setTimeout(r, 1500 * attempt));
    }
  }
}

// remove clips for lines that no longer exist
const wanted = new Set(Object.values(map).map((f) => f.split("/").pop()));
for (const f of readdirSync(OUT)) if (!wanted.has(f)) unlinkSync(`${OUT}/${f}`);

const entries = Object.entries(map).map(([text, file]) => `  ${JSON.stringify(text)}: ${JSON.stringify(file)},`);
writeFileSync(
  "data/voiceFiles.ts",
  `// Generated by \`npm run audio\`. Maps each narration line (its \`ur\` key) to its local MP3 file.\nexport const VOICE_FILES: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Done: ${lines.size} lines, ${made} new files.`);
